    alter table public.questionnaire_responses
      add constraint questionnaire_schema_version_check check (schema_version between 1 and 99);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'questionnaire_response_object_check') then
    alter table public.questionnaire_responses
      add constraint questionnaire_response_object_check check (jsonb_typeof(response_data) = 'object');
  end if;
  if not exists (select 1 from pg_constraint where conname = 'questionnaire_response_size_check') then
    alter table public.questionnaire_responses
      add constraint questionnaire_response_size_check check (octet_length(response_data::text) <= 100000);
  end if;
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.questionnaire_responses'::regclass
      and conname = 'questionnaire_consult_code_check'
